/** Picks a pair not yet played this session, starting over once all have been used. */
export function pickWordPair(
  usedIndexes: readonly number[],
  rng: Rng = Math.random,
): { pair: WordPair; usedIndexes: number[] } {
  const used = usedIndexes.length >= WORD_PAIRS.length ? [] : usedIndexes;
  const available = WORD_PAIRS.map((_, i) => i).filter((i) => !used.includes(i));
  const index = available[Math.floor(rng() * available.length)];
  return { pair: WORD_PAIRS[index], usedIndexes: [...used, index] };
}
